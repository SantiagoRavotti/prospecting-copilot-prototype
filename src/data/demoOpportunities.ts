function buildOpportunity(seed: OppSeed): Opportunity {
  const eligibility: OpportunityEligibility = {
    consortiumRequired: false,
    localPartnerRequired: false,
    ...seed.eligibility,
  };
  const deadline = seed.deadlineDays == null ? undefined : daysFromNow(seed.deadlineDays);
  const { score, level, factors } = scoreOpportunity({
    title: seed.title,
    topics: seed.topics,
    services: seed.services,
    organization: seed.organization,
    country: seed.country,
    region: seed.region,
    summary: seed.summary,
    budgetMaxEur: seed.budgetMaxEur,
    deadline,
    eligibility,
  });

  const suggestedServices = seed.services.slice(0, 4);
  const risks =
    seed.risks ??
    (eligibility.consortiumRequired || eligibility.localPartnerRequired
      ? ['Partnering requirement — identify partners early.']
      : []);

  return {
    id: uid(),
    title: seed.title,
    organization: seed.organization,
    funder: seed.funder,
    program: undefined,
    reference: seed.reference,
    url: 'https://example.com/demo-opportunity',
    sourceName: seed.sourceName,
    type: seed.type,
    contractType: undefined,
    topics: seed.topics,
    services: seed.services,
    country: seed.country,
    region: seed.region,
    language: seed.language,
    publishedAt: daysFromNow(-(7 + ((seed.title.length * 3) % 20))),
    questionsDeadline: undefined,
    deadline,
    startDate: undefined,
    durationMonths: seed.durationMonths,
    foundAt: nowIso(),
    lastCheckedAt: nowIso(),
    budgetMinEur: seed.budgetMinEur,
    budgetMaxEur: seed.budgetMaxEur,
    currency: 'EUR',
    eligibility,
    procedure: seed.procedure,
    evaluationCriteria: seed.evaluationCriteria,
    expertProfiles: seed.expertProfiles ?? [],
    deliverables: seed.deliverables ?? [],
    documents: [
      { label: 'Original publication (demo link)', url: 'https://example.com/demo-opportunity' },
    ],
    summary: seed.summary,
    scopeOfWork: seed.scopeOfWork,
    relevanceRationale:
      factors
        .filter((f) => f.points / f.max >= 0.6)
        .slice(0, 3)
        .map((f) => f.reason)
        .join(' ') || 'Limited overlap with Impact Hydrogen positioning.',
    suggestedServices,
    risks,
    nextSteps: [
      'Download and review the terms of reference.',
      'Confirm eligibility.',
      ...(eligibility.consortiumRequired || eligibility.localPartnerRequired
        ? ['Identify potential partners.']
        : []),
      'Request an internal bid/no-bid decision.',
    ],
    score,
    matchLevel: level,
    matchFactors: factors,
    status: 'new',
    saved: false,
    assignee: undefined,
    notes: '',
    history: [{ at: nowIso(), event: 'Demo opportunity seeded — fictional data.' }],
    deliveryEstimate: undefined,
    isDemo: true,
  };
}

export function buildDemoOpportunities(): Opportunity[] {
  return SEEDS.map(buildOpportunity);
}

